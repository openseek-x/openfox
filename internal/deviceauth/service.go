// Package deviceauth implements the device challenge-response boundary.
// Device credentials and sessions are deliberately separate from identity's
// user credentials and sessions.
package deviceauth

import (
	"bytes"
	"context"
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/binary"
	"errors"
	"strings"
	"time"
	"unicode"

	"openfox/internal/identity"
	"openfox/internal/tenancy"
)

const (
	DefaultChallengeTTL    = 5 * time.Minute
	DefaultSessionAbsolute = 24 * time.Hour
	challengeBytesSize     = 32
	nonceSize              = 32
	maxTokenLength         = 128
)

var (
	ErrInvalidRequest          = errors.New("deviceauth: invalid request")
	ErrDeviceUnauthenticated   = errors.New("deviceauth: device is not authenticated")
	ErrChallengeNotFound       = errors.New("deviceauth: challenge not found")
	ErrChallengeConflict       = errors.New("deviceauth: challenge is stale or already consumed")
	ErrInvalidSignature        = errors.New("deviceauth: signature is invalid")
	ErrSessionNotFound         = errors.New("deviceauth: device session not found")
	ErrOrganizationNotFound    = errors.New("deviceauth: organization grant not found")
	ErrDeviceAlreadyRegistered = errors.New("deviceauth: device is already registered")
)

// Challenge is the server-side challenge record. Raw bytes never need to be
// logged; the API encodes them only for transport to the device.
type Challenge struct {
	ID        string
	DeviceID  string
	KeyID     string
	Nonce     []byte
	Challenge []byte
	ExpiresAt time.Time
	CreatedAt time.Time
}

type ChallengeRequest struct {
	DeviceID string
	KeyID    string
}

type ChallengeResult struct {
	ID        string
	DeviceID  string
	KeyID     string
	Nonce     []byte
	Challenge []byte
	ExpiresAt time.Time
}

type VerifyRequest struct {
	ChallengeID string
	DeviceID    string
	KeyID       string
	Signature   []byte
}

// PendingSession contains only values generated by the service and the
// request binding. The store fills the device and key generations from the
// locked challenge rows before inserting the session.
type PendingSession struct {
	DeviceID  string
	KeyID     string
	TokenHash []byte
	IssuedAt  time.Time
	ExpiresAt time.Time
}

type Session struct {
	ID               string
	DeviceID         string
	KeyID            string
	DeviceGeneration int64
	KeyGeneration    int64
	IssuedAt         time.Time
	ExpiresAt        time.Time
}

type SessionResult struct {
	DeviceID  string
	Token     string
	ExpiresAt time.Time
}

type Principal struct {
	SessionID        string
	DeviceID         string
	KeyID            string
	DeviceGeneration int64
	KeyGeneration    int64
	ExpiresAt        time.Time
}

type Registration struct {
	Organization tenancy.OrganizationSelection
	DeviceKey    string
	Name         string
	InstallID    string
	KeyID        string
	PublicKey    ed25519.PublicKey
	MaxSlots     int
}

// SignatureVerifier is called while the store holds the challenge row lock.
// This keeps verification and one-time consumption in one transaction.
type SignatureVerifier func(publicKey ed25519.PublicKey, payload, signature []byte) bool

type Store interface {
	CreateChallenge(context.Context, Challenge) error
	ConsumeChallenge(context.Context, VerifyRequest, PendingSession, time.Time, SignatureVerifier) (Session, error)
	AuthenticateSession(context.Context, []byte, time.Time) (Session, error)
	SelectOrganization(context.Context, string, string) (tenancy.OrganizationSelection, error)
	RegisterDevice(context.Context, Registration) (string, error)
	RevokeGrant(context.Context, tenancy.OrganizationSelection, string, time.Time) error
	RevokeDevice(context.Context, string, time.Time) error
	RevokeKey(context.Context, string, string, time.Time) error
}

type Service struct {
	Store           Store
	ChallengeTTL    time.Duration
	SessionAbsolute time.Duration
	Now             func() time.Time
}

func (s Service) IssueChallenge(ctx context.Context, request ChallengeRequest) (ChallengeResult, error) {
	deviceID, keyID, err := normalizeCredentialBinding(request.DeviceID, request.KeyID)
	if err != nil {
		return ChallengeResult{}, err
	}
	if s.Store == nil || s.Now == nil {
		return ChallengeResult{}, errors.New("deviceauth: service is not configured")
	}
	ttl := s.ChallengeTTL
	if ttl == 0 {
		ttl = DefaultChallengeTTL
	}
	if ttl <= 0 || ttl > DefaultChallengeTTL {
		return ChallengeResult{}, ErrInvalidRequest
	}
	id, err := newUUID()
	if err != nil {
		return ChallengeResult{}, err
	}
	nonce, err := randomBytes(nonceSize)
	if err != nil {
		return ChallengeResult{}, err
	}
	challengeBytes, err := randomBytes(challengeBytesSize)
	if err != nil {
		return ChallengeResult{}, err
	}
	now := s.Now().UTC()
	challenge := Challenge{
		ID:        id,
		DeviceID:  deviceID,
		KeyID:     keyID,
		Nonce:     nonce,
		Challenge: challengeBytes,
		CreatedAt: now,
		ExpiresAt: now.Add(ttl),
	}
	if err := s.Store.CreateChallenge(ctx, challenge); err != nil {
		return ChallengeResult{}, err
	}
	return ChallengeResult{
		ID:        challenge.ID,
		DeviceID:  challenge.DeviceID,
		KeyID:     challenge.KeyID,
		Nonce:     append([]byte(nil), challenge.Nonce...),
		Challenge: append([]byte(nil), challenge.Challenge...),
		ExpiresAt: challenge.ExpiresAt,
	}, nil
}

func (s Service) Verify(ctx context.Context, request VerifyRequest) (SessionResult, error) {
	challengeID, err := normalizeUUID(request.ChallengeID)
	if err != nil {
		return SessionResult{}, ErrInvalidRequest
	}
	deviceID, keyID, err := normalizeCredentialBinding(request.DeviceID, request.KeyID)
	if err != nil || len(request.Signature) != ed25519.SignatureSize {
		return SessionResult{}, ErrInvalidRequest
	}
	if s.Store == nil || s.Now == nil {
		return SessionResult{}, errors.New("deviceauth: service is not configured")
	}
	absolute := s.SessionAbsolute
	if absolute == 0 {
		absolute = DefaultSessionAbsolute
	}
	if absolute <= 0 {
		return SessionResult{}, ErrInvalidRequest
	}
	token, tokenHash, err := identity.NewSessionToken()
	if err != nil {
		return SessionResult{}, err
	}
	now := s.Now().UTC()
	_, err = s.Store.ConsumeChallenge(ctx, VerifyRequest{
		ChallengeID: challengeID,
		DeviceID:    deviceID,
		KeyID:       keyID,
		Signature:   append([]byte(nil), request.Signature...),
	}, PendingSession{
		DeviceID:  deviceID,
		KeyID:     keyID,
		TokenHash: append([]byte(nil), tokenHash...),
		IssuedAt:  now,
		ExpiresAt: now.Add(absolute),
	}, now, func(publicKey ed25519.PublicKey, payload, signature []byte) bool {
		return ed25519.Verify(publicKey, payload, signature)
	})
	if err != nil {
		return SessionResult{}, err
	}
	return SessionResult{DeviceID: deviceID, Token: token, ExpiresAt: now.Add(absolute)}, nil
}

func (s Service) Authenticate(ctx context.Context, token string) (Principal, error) {
	if s.Store == nil || s.Now == nil {
		return Principal{}, ErrSessionNotFound
	}
	token = strings.TrimSpace(token)
	if token == "" || len(token) > maxTokenLength {
		return Principal{}, ErrSessionNotFound
	}
	session, err := s.Store.AuthenticateSession(ctx, identity.HashSessionToken(token), s.Now().UTC())
	if err != nil {
		if errors.Is(err, ErrSessionNotFound) {
			return Principal{}, ErrSessionNotFound
		}
		return Principal{}, err
	}
	return Principal{
		SessionID:        session.ID,
		DeviceID:         session.DeviceID,
		KeyID:            session.KeyID,
		DeviceGeneration: session.DeviceGeneration,
		KeyGeneration:    session.KeyGeneration,
		ExpiresAt:        session.ExpiresAt,
	}, nil
}

func (s Service) SelectOrganization(ctx context.Context, deviceID, organizationID string) (tenancy.OrganizationSelection, error) {
	deviceID, err := normalizeUUID(deviceID)
	if err != nil {
		return tenancy.OrganizationSelection{}, ErrInvalidRequest
	}
	organizationID, err = normalizeUUID(organizationID)
	if err != nil {
		return tenancy.OrganizationSelection{}, ErrInvalidRequest
	}
	if s.Store == nil {
		return tenancy.OrganizationSelection{}, errors.New("deviceauth: service is not configured")
	}
	selection, err := s.Store.SelectOrganization(ctx, deviceID, organizationID)
	if err != nil {
		if errors.Is(err, ErrOrganizationNotFound) {
			return tenancy.OrganizationSelection{}, ErrOrganizationNotFound
		}
		return tenancy.OrganizationSelection{}, err
	}
	if selection.OrganizationID != organizationID || selection.ActorID != deviceID || selection.AuthorizationVersion == 0 {
		return tenancy.OrganizationSelection{}, ErrOrganizationNotFound
	}
	return selection, nil
}

func (s Service) RegisterDevice(ctx context.Context, registration Registration) (string, error) {
	if err := validateSelection(registration.Organization); err != nil {
		return "", ErrInvalidRequest
	}
	deviceKey, err := normalizeText(registration.DeviceKey, 255)
	if err != nil {
		return "", ErrInvalidRequest
	}
	name := registration.Name
	if name == "" {
		name = "Unnamed device"
	}
	name, err = normalizeText(name, 255)
	if err != nil {
		return "", ErrInvalidRequest
	}
	installID := registration.InstallID
	if installID != "" {
		installID, err = normalizeText(installID, 255)
		if err != nil {
			return "", ErrInvalidRequest
		}
	}
	keyID, err := normalizeText(registration.KeyID, 128)
	if err != nil {
		return "", ErrInvalidRequest
	}
	if len(registration.PublicKey) != ed25519.PublicKeySize {
		return "", ErrInvalidRequest
	}
	maxSlots := registration.MaxSlots
	if maxSlots == 0 {
		maxSlots = 1
	}
	if maxSlots < 1 || maxSlots > 1024 {
		return "", ErrInvalidRequest
	}
	if s.Store == nil {
		return "", errors.New("deviceauth: service is not configured")
	}
	return s.Store.RegisterDevice(ctx, Registration{
		Organization: registration.Organization,
		DeviceKey:    deviceKey,
		Name:         name,
		InstallID:    installID,
		KeyID:        keyID,
		PublicKey:    append(ed25519.PublicKey(nil), registration.PublicKey...),
		MaxSlots:     maxSlots,
	})
}

func (s Service) RevokeGrant(ctx context.Context, selection tenancy.OrganizationSelection, deviceID string, now time.Time) error {
	if err := validateSelection(selection); err != nil {
		return ErrInvalidRequest
	}
	deviceID, err := normalizeUUID(deviceID)
	if err != nil {
		return ErrInvalidRequest
	}
	if s.Store == nil {
		return errors.New("deviceauth: service is not configured")
	}
	return s.Store.RevokeGrant(ctx, selection, deviceID, now.UTC())
}

func (s Service) RevokeDevice(ctx context.Context, deviceID string, now time.Time) error {
	deviceID, err := normalizeUUID(deviceID)
	if err != nil {
		return ErrInvalidRequest
	}
	if s.Store == nil {
		return errors.New("deviceauth: service is not configured")
	}
	return s.Store.RevokeDevice(ctx, deviceID, now.UTC())
}

func (s Service) RevokeKey(ctx context.Context, deviceID, keyID string, now time.Time) error {
	deviceID, keyID, err := normalizeCredentialBinding(deviceID, keyID)
	if err != nil {
		return ErrInvalidRequest
	}
	if s.Store == nil {
		return errors.New("deviceauth: service is not configured")
	}
	return s.Store.RevokeKey(ctx, deviceID, keyID, now.UTC())
}

// CanonicalPayload is the versioned, length-prefixed payload signed by the
// device. Length prefixes prevent concatenation ambiguity between identifiers.
func CanonicalPayload(challengeID, deviceID, keyID string, nonce, challenge []byte) []byte {
	var payload bytes.Buffer
	payload.WriteString("openfox-device-auth-v1")
	writeCanonicalString(&payload, challengeID)
	writeCanonicalString(&payload, deviceID)
	writeCanonicalString(&payload, keyID)
	writeCanonicalBytes(&payload, nonce)
	writeCanonicalBytes(&payload, challenge)
	return payload.Bytes()
}

func EncodeBase64URL(value []byte) string {
	return base64.RawURLEncoding.EncodeToString(value)
}

func DecodeBase64URL(value string, expectedLength int) ([]byte, error) {
	if value == "" || len(value) > 4096 {
		return nil, ErrInvalidRequest
	}
	decoded, err := base64.RawURLEncoding.DecodeString(value)
	if err != nil || (expectedLength > 0 && len(decoded) != expectedLength) {
		return nil, ErrInvalidRequest
	}
	return decoded, nil
}

func validateSelection(selection tenancy.OrganizationSelection) error {
	if _, err := tenancy.NewTenantContext(selection, tenancy.SourceUserRequest); err != nil {
		return err
	}
	return nil
}

func normalizeCredentialBinding(deviceID, keyID string) (string, string, error) {
	deviceID, err := normalizeUUID(deviceID)
	if err != nil {
		return "", "", ErrInvalidRequest
	}
	keyID, err = normalizeText(keyID, 128)
	if err != nil {
		return "", "", ErrInvalidRequest
	}
	return deviceID, keyID, nil
}

func normalizeText(value string, limit int) (string, error) {
	if value == "" || value != strings.TrimSpace(value) || len(value) > limit {
		return "", ErrInvalidRequest
	}
	for _, character := range value {
		if unicode.IsControl(character) || unicode.IsSpace(character) {
			return "", ErrInvalidRequest
		}
	}
	return value, nil
}

func normalizeUUID(value string) (string, error) {
	if len(value) != 36 {
		return "", ErrInvalidRequest
	}
	for index, character := range value {
		if index == 8 || index == 13 || index == 18 || index == 23 {
			if character != '-' {
				return "", ErrInvalidRequest
			}
			continue
		}
		if !((character >= '0' && character <= '9') ||
			(character >= 'a' && character <= 'f') ||
			(character >= 'A' && character <= 'F')) {
			return "", ErrInvalidRequest
		}
	}
	return strings.ToLower(value), nil
}

func newUUID() (string, error) {
	value, err := randomBytes(16)
	if err != nil {
		return "", err
	}
	value[6] = (value[6] & 0x0f) | 0x40
	value[8] = (value[8] & 0x3f) | 0x80
	return formatUUID(value), nil
}

func randomBytes(length int) ([]byte, error) {
	value := make([]byte, length)
	if _, err := rand.Read(value); err != nil {
		return nil, err
	}
	return value, nil
}

func formatUUID(value []byte) string {
	return strings.ToLower(
		valueToHex(value[0:4]) + "-" +
			valueToHex(value[4:6]) + "-" +
			valueToHex(value[6:8]) + "-" +
			valueToHex(value[8:10]) + "-" +
			valueToHex(value[10:16]),
	)
}

func valueToHex(value []byte) string {
	const digits = "0123456789abcdef"
	result := make([]byte, len(value)*2)
	for index, item := range value {
		result[index*2] = digits[item>>4]
		result[index*2+1] = digits[item&0x0f]
	}
	return string(result)
}

func writeCanonicalString(buffer *bytes.Buffer, value string) {
	writeCanonicalBytes(buffer, []byte(value))
}

func writeCanonicalBytes(buffer *bytes.Buffer, value []byte) {
	var length [4]byte
	binary.BigEndian.PutUint32(length[:], uint32(len(value)))
	buffer.Write(length[:])
	buffer.Write(value)
}
